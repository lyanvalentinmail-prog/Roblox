"""Bundle the local command modules without HTTP or runtime require calls."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent.parent

def bundle():
    source = (ROOT / 'Main.client.lua').read_text()
    begin = '-- COMMAND_MODULES_BEGIN'
    end = '-- COMMAND_MODULES_END'
    before, rest = source.split(begin, 1)
    _, after = rest.split(end, 1)
    modules = []
    for path in sorted((ROOT / 'commands').glob('*.lua')):
        modules.append(f'commands["{path.stem}"] = (function()\n{path.read_text()}\nend)()')
    return '-- GENERATED by python3 tools/build.py; edit Main.client.lua or commands/*.lua.\n' + before + '\n'.join(modules) + after

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'Commands.client.lua'
    result = bundle()
    if args.check:
        if output.read_text() != result:
            raise SystemExit('Bundle desactualizado: ejecuta python3 tools/build.py')
        print('Bundle actualizado.')
    else:
        output.write_text(result)
        print('Commands.client.lua generado.')
